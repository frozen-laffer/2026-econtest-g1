/* ─── 单次采集: DMA 完成回调 ───────────────────────────────────────────
 *
 *  三路 ADC1/ADC2/ADC5 由 TIM8 的 UPDATE / CC1 / OC2REF 分别触发,
 *  相位 0 / 1/3 / 2/3, 每次采集各 N 点。
 *  DMA 使用 NORMAL 模式, 所以只有 TC 中断, 没有 HT。
 *  任一路完成即向 scope_acq 报告, 由它判断三路是否全齐。
 * ---------------------------------------------------------------------- */
static inline uint8_t adc_ch_of(ADC_HandleTypeDef *hadc)
{
    if (hadc->Instance == ADC1) return 0;
    if (hadc->Instance == ADC2) return 1;
    if (hadc->Instance == ADC5) return 2;
    return 0xFF;
}

void HAL_ADC_ConvCpltCallback(ADC_HandleTypeDef* hadc)
{
    uint8_t ch = adc_ch_of(hadc);
    if (ch > 2) return;
    ScopeAcq_OnCplt(ch);
}

void HAL_ADC_ConvHalfCpltCallback(ADC_HandleTypeDef* hadc)
{
    (void)hadc;   /* NORMAL 模式不产生半满事件 */
}

